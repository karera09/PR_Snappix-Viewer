def cpython_license_text() -> str:
    """The build interpreter's own LICENSE.txt, reproduced verbatim.

    ``sys.base_prefix`` is the real CPython installation even when running
    inside a venv, i.e. exactly the runtime PyInstaller freezes into the
    dist. The PSF license requires retaining the license text, so reproduce
    it rather than merely linking to python.org.
    """
    for name in ("LICENSE.txt", "LICENSE"):
        path = Path(sys.base_prefix) / name
        if path.is_file():
            return path.read_text(encoding="utf-8", errors="replace").rstrip("\n")
    return (
        "(The build interpreter did not ship a LICENSE file on disk; the\n"
        "PSF License Agreement is available at https://docs.python.org/3/license.html)"
    )


def indent(text: str, spaces: int) -> str:
    pad = " " * spaces
    return "\n".join(pad + ln if ln else ln for ln in text.splitlines())


