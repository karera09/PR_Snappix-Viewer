"""Generate ``THIRD_PARTY_LICENSES.txt`` for the plain portable viewer.

This module has two jobs:

1. **The viewer's own notice** (:func:`generate` / the CLI): the notice file
   shipped with the plain distribution (``dist/snappix-viewer/``) and
   committed at the repo root.  Its package set is the *explicit dependency
   closure* of pyproject's ``[project.dependencies]`` (minus
   :data:`VIEWER_EXCLUDED` — numpy is excluded from the frozen viewer by
   ``snappix_viewer.spec``), so plugin-only dependencies (torch/CUDA, a
   plugin's vendored closure, …) never appear.  The viewer-only public
   snapshot (``tools/public_export.py`` — no ``plugins/``) is therefore
   fully self-describing.
2. **A reusable harvesting library** for the plugins' own notices: each
   separately-distributed plugin pack carries its own
   ``THIRD_PARTY_LICENSES.txt``, generated at build time by the plugin's
   ``build_hook.py`` (``plugins/<id>/build_hook.py``) from the helpers
   exported here (:func:`dependency_closure`, :func:`package_sections`,
   :func:`full_texts`, :func:`banner`, …).

The harvesting approach (shared by every notice):

* Reproduce the license text each bundled Python package ships in its
  ``*.dist-info`` metadata (the authoritative per-package copyright line +
  permission text — reproducing it verbatim is exactly what MIT / BSD /
  Apache / ISC / MPL / etc. require).
* Prepend hand-authored sections that ``dist-info`` cannot provide (bundled
  native components, copyleft-compliance statements).  Packages whose wheel
  ships **no** license file in dist-info (loguru) get the canonical upstream
  text from :data:`FALLBACK_LICENSE_TEXTS`.
* Append the canonical GNU **LGPL-3.0** and **GPL-3.0** full texts (read
  from ``licenses/`` — PySide6's wheel ships only its *commercial* license
  reference, not the open-source text, so we keep the canonical copies in
  the repo).

Usage::

    uv run python tools/gen_third_party_licenses.py          # refresh the
                                                             # committed file
    uv run python tools/gen_third_party_licenses.py <path>   # write elsewhere

``build_portable.py`` also imports :func:`generate` so the shipped ``dist/``
always carries a notice matching exactly the packages that were frozen in.
"""

