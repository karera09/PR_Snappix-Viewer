def norm(name: str) -> str:
    """PEP 503-ish normalisation (lowercase, ``_`` → ``-``)."""
    return name.lower().replace("_", "-")


def distinfo_dir(dist: im.Distribution) -> Path | None:
    """The distribution's ``*.dist-info`` directory, when it has one on disk.

    Public because the plugins' build hooks need the same anchor (the
    per-package license text and the installed payload both live next to it).
    """
    path = getattr(dist, "_path", None)
    if path is not None:
        return Path(path)
    return None


def dist_top_level_import_names(dist: im.Distribution) -> set[str]:
    """Top-level import names a distribution installs (packages + modules).

    Prefers the authoritative ``top_level.txt``; otherwise derives them from
    the installed file list, so ``Pillow`` → ``PIL`` and ``markdown-it-py`` →
    ``markdown_it``.  Extension modules carrying an ABI tag
    (``_cffi_backend.cp312-win_amd64.pyd``) collapse to their import name, and
    bogus ``..`` script paths / ``*.dist-info`` / ``*.data`` entries drop out.

    Two build-time consumers need exactly this mapping and used to carry a
    copy each: the host's unlicensed-package check (frozen top-level names →
    the notice's dependency closure) and plugin vendoring (which
    payload directories/files to copy next to the pack).
    """
    info = distinfo_dir(dist)
    if info is not None:
        tl = info / "top_level.txt"
        if tl.is_file():
            names = {
                ln.strip().split("/")[0]
                for ln in tl.read_text(encoding="utf-8").splitlines()
                if ln.strip() and ln.strip() != ".."
            }
            if names:
                return names
    names = set()
    for f in dist.files or []:
        parts = f.parts
        if not parts or parts[0] == "..":
            continue
        first = parts[0]
        if first.endswith((".dist-info", ".data")):
            continue
        if len(parts) == 1:
            if first.endswith((".py", ".pyd", ".so", ".pyi")):
                names.add(first.split(".")[0])
        else:
            names.add(first)
    names.discard("")
    return names


def license_files(dist: im.Distribution) -> list[Path]:
    """Return the on-disk license/notice files a distribution ships."""
    info = distinfo_dir(dist)
    if info is None or not info.is_dir():
        return []
    out: list[Path] = []
    for p in sorted(info.rglob("*")):
        if not p.is_file():
            continue
        low = p.name.lower()
        if not any(tok in low for tok in _LICENSE_FILE_TOKENS):
            continue
        if any(skip in low for skip in _LICENSE_FILE_SKIP):
            continue
        # RECORD / METADATA / WHEEL etc. never match the tokens above, so this
        # is just the license/notice/authors set.
        out.append(p)
    return out


def spdx(dist: im.Distribution) -> str:
    md = dist.metadata
    expr = md.get("License-Expression")
    if expr:
        return expr.strip()
    classifiers = [
        c.split("::")[-1].strip()
        for c in md.get_all("Classifier", []) or []
        if c.startswith("License ::")
    ]
    if classifiers:
        return " / ".join(dict.fromkeys(classifiers))
    lic = (md.get("License") or "").strip()
    if lic and len(lic) <= 60 and "\n" not in lic:
        return lic
    return "(see license text below)"


def embedded_license_banners(
    dist: im.Distribution, embedded_files: dict[str, list[str]]
) -> list[str]:
    """Return license banner comments embedded in a package's data files.

    Some packages vendor third-party code as *data files* (not as separate
    installed distributions) whose license text lives in a leading
    ``/* ... */`` banner (e.g. minified JS bundles), so importlib.metadata
    never sees them.  *embedded_files* maps normalized dist name → data files
    to scan; the caller (a plugin's notice generator) supplies the map for
    the packages it actually vendors.
    """
    import re

    key = norm(dist.metadata.get("Name", ""))
    rels = embedded_files.get(key)
    if not rels:
        return []
    banners: list[str] = []
    for rel in rels:
        try:
            text = Path(dist.locate_file(rel)).read_text(
                encoding="utf-8", errors="replace"
            )
        except OSError:
            continue
        for m in re.finditer(r"/\*(.*?)\*/", text, re.S):
            block = m.group(1)
            if "Bundled Dependencies" in block or (
                "License" in block and "Copyright" in block
            ):
                # Strip a leading decorative "!" and per-line " * " gutters.
                lines = [
                    ln[3:] if ln.startswith(" * ") else ln.lstrip(" *")
                    for ln in block.splitlines()
                ]
                cleaned = "\n".join(lines).strip("!\n ")
                if cleaned not in banners:
                    banners.append(cleaned)
    return banners


def _windows_target_environment() -> dict:
    """The marker environment of the SHIPPED platform (Windows portable exe).

    Dependency markers must be evaluated against the platform the product
    ships on, not the machine the notice happens to be generated on —
    otherwise the package set (and therefore the committed
    THIRD_PARTY_LICENSES.txt) silently diverges between a Linux dev box and
    the Windows CI/build runner (e.g. loguru's ``colorama`` /
    ``win32-setctime``, both ``sys_platform == 'win32'``-gated).
    """
    from packaging.markers import default_environment

    env = dict(default_environment())
    env.update(
        {
            "sys_platform": "win32",
            "platform_system": "Windows",
            "os_name": "nt",
            "platform_machine": "AMD64",
        }
    )
    return env


def dependency_closure(
    roots: list[tuple[str, set[str]]], env: dict | None = None
) -> set[str]:
    """Transitive runtime dependency closure of *roots* (normalized names).

    *roots* is a list of ``(dist_name, extras_to_follow)``.  Requirements are
    parsed with :mod:`packaging` and their markers evaluated against the
    SHIPPED platform (:func:`_windows_target_environment` — deterministic
    across dev/CI operating systems) unless *env* overrides it; an
    ``extra == '…'`` requirement is followed only when that extra was
    requested for the dist declaring it (so httpx[http2] pulls h2 but not
    httpx's cli/brotli extras).  Missing dists are silently skipped — the
    caller decides whether absence is an error.
    """
    from collections import deque

    from packaging.requirements import Requirement

    if env is None:
        env = _windows_target_environment()

    resolved: dict[str, frozenset[str]] = {}
    queue: deque[tuple[str, frozenset[str]]] = deque(
        (norm(name), frozenset(extras)) for name, extras in roots
    )
    result: set[str] = set()
    while queue:
        key, extras = queue.popleft()
        prev = resolved.get(key)
        if prev is not None and extras <= prev:
            continue
        merged = (prev or frozenset()) | extras
        resolved[key] = merged
        result.add(key)
        try:
            dist = im.distribution(key)
        except im.PackageNotFoundError:
            continue
        for rstr in dist.requires or []:
            try:
                req = Requirement(rstr)
            except Exception:
                continue
            marker = req.marker
            include = marker is None or marker.evaluate({**env, "extra": ""})
            if not include:
                include = any(
                    marker.evaluate({**env, "extra": e}) for e in merged
                )
            if include:
                # Carry the requirement's bracket extras (``foo[bar]``) into the
                # closure so a transitive dist's *conditional* dependencies are
                # followed too — dropping them here would silently omit the
                # ``bar`` extra's deps from both the vendored closure and the
                # license notice.
                queue.append((norm(req.name), frozenset(req.extras)))
    return result


def pyproject_dependency_roots(
    pyproject: Path, extra: str | None = None
) -> list[tuple[str, set[str]]]:
    """Direct dependencies declared in *pyproject* as closure roots.

    ``[project.dependencies]``, or the ``extra`` optional-dependencies group
    when given.  Extras requested in the requirement string (``httpx[http2]``
    style) are carried into the closure; version specifiers are ignored (the
    closure is computed against the installed venv, whose versions uv.lock
    pins).
    """
    import re

    project = tomllib.loads(pyproject.read_text(encoding="utf-8"))["project"]
    reqs = (
        project.get("optional-dependencies", {}).get(extra, [])
        if extra
        else project.get("dependencies", [])
    )
    roots: list[tuple[str, set[str]]] = []
    for req in reqs:
        m = re.match(r"\s*([A-Za-z0-9._-]+)\s*(?:\[([^\]]*)\])?", req)
        if not m:
            continue
        name = m.group(1)
        extras = {
            e.strip() for e in (m.group(2) or "").split(",") if e.strip()
        }
        roots.append((name, extras))
    return roots


def pyproject_main_dependency_roots() -> list[tuple[str, set[str]]]:
    """The viewer's direct dependencies from pyproject ``[project.dependencies]``."""
    return pyproject_dependency_roots(ROOT / "pyproject.toml")


def distributions_by_names(names: list[str]) -> list[im.Distribution]:
    """Resolve normalized dist names to Distribution objects (sorted, deduped).

    Names not installed in the current environment are skipped.
    """
    seen: dict[str, im.Distribution] = {}
    for name in names:
        key = norm(name)
        if key in seen:
            continue
        try:
            seen[key] = im.distribution(key)
        except im.PackageNotFoundError:
            continue
    return [seen[k] for k in sorted(seen)]


def viewer_distribution_names() -> list[str]:
    """The plain viewer's bundled package set (normalized names, sorted)."""
    closure = dependency_closure(pyproject_main_dependency_roots())
    return sorted(closure - {norm(n) for n in VIEWER_EXCLUDED})


class _AbsentDistribution:
    """Stand-in for a closure member whose wheel is absent from this venv.

    The closure targets the shipped platform (Windows), so a Linux dev venv
    legitimately lacks the ``sys_platform == 'win32'`` members (uv honours
    the marker).  Their notice entry still must appear — the version comes
    from the committed uv.lock (the authoritative pin the Windows build
    installs) and the license text from :data:`FALLBACK_LICENSE_TEXTS`.
    Duck-types the small ``importlib.metadata.Distribution`` surface the
    section builder reads (``metadata.get`` / no ``_path`` → no on-disk
    license files → fallback text).
    """

    def __init__(self, name: str, version: str) -> None:
        self._md = {
            "Name": name,
            "Version": version,
            "License-Expression": _FALLBACK_SPDX.get(norm(name), ""),
        }

    @property
    def metadata(self):
        return self

    def get(self, key: str, default=None):
        return self._md.get(key, default)

    def get_all(self, key: str, default=None):
        return default


def _uv_lock_version(name: str) -> str:
    """The version uv.lock pins for *name* ('' when absent from the lock)."""
    lock_path = ROOT / "uv.lock"
    if not lock_path.is_file():
        return ""
    data = tomllib.loads(lock_path.read_text(encoding="utf-8"))
    for pkg in data.get("package", []):
        if norm(pkg.get("name", "")) == norm(name):
            return pkg.get("version", "")
    return ""


