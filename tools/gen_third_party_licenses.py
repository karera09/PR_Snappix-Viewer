def package_sections(
    dists: list[im.Distribution],
    intro: str,
    *,
    copyleft_handled: set[str] | None = None,
    embedded_files: dict[str, list[str]] | None = None,
) -> str:
    """Section 3 — per-package license texts for *dists*.

    *copyleft_handled* names dists whose notice is the hand-authored
    compliance section (Qt/PySide6); *embedded_files* optionally maps dist
    names to data files whose embedded license banners should be harvested
    (see :func:`embedded_license_banners`).
    """
    handled = copyleft_handled if copyleft_handled is not None else COPYLEFT_HANDLED
    parts: list[str] = [banner("3. Bundled Python packages")]
    parts.append(intro)
    for dist in dists:
        name = dist.metadata.get("Name")
        version = dist.metadata.get("Version", "")
        key = norm(name)
        head = f"\n{'-' * 78}\n{name}  {version}\nSPDX/License: {spdx(dist)}\n{'-' * 78}\n"
        parts.append(head)
        if key in handled:
            parts.append(
                "Used under the GNU LGPL v3 — see section 2 (Copyleft compliance "
                "notices)\nand section 4 (full LGPL v3 / GPL v3 texts).\n"
            )
            continue
        files = license_files(dist)
        if not files and key in FALLBACK_LICENSE_TEXTS:
            parts.append(
                "[license text reproduced from the upstream project — this "
                "package's wheel\nships no license file in its metadata]\n"
                f"{FALLBACK_LICENSE_TEXTS[key]}\n"
            )
        elif not files:
            parts.append(
                "(No license file shipped in this package's metadata; the "
                "SPDX identifier above\nrecords its license.)\n"
            )
        for f in files:
            text = f.read_text(encoding="utf-8", errors="replace").rstrip("\n")
            parts.append(f"[{f.name}]\n{text}\n")
        if embedded_files:
            for banner_text in embedded_license_banners(dist, embedded_files):
                parts.append(f"[bundled dependencies]\n{banner_text}\n")
    return "\n".join(parts)


def full_texts() -> str:
    out = [banner("4. Full license texts")]
    for label, fname in (
        ("GNU LESSER GENERAL PUBLIC LICENSE, Version 3", "LGPL-3.0.txt"),
        ("GNU GENERAL PUBLIC LICENSE, Version 3", "GPL-3.0.txt"),
    ):
        path = LICENSES_DIR / fname
        if not path.is_file():
            raise SystemExit(
                f"[gen-licenses] missing canonical text: {path}. "
                "Restore it (e.g. curl https://www.gnu.org/licenses/"
                f"{fname.lower()})."
            )
        text = path.read_text(encoding="utf-8").rstrip("\n")
        out.append(f"\n{'-' * 78}\n{label}\n{'-' * 78}\n{text}\n")
    return "\n".join(out)


_PACKAGES_INTRO = (
    "Each package below is reproduced with the exact license / notice text\n"
    "it ships in its distribution metadata. Qt/PySide6 components are\n"
    "routed to the LGPL compliance notice in section 2. For packages whose\n"
    "wheel ships no license file, the canonical upstream text is\n"
    "reproduced instead.  The set is the dependency closure of the viewer\n"
    "app (pyproject [project.dependencies]); numpy is absent by design (the\n"
    "frozen viewer excludes it — it ships only inside the AI plugin pack,\n"
    "whose own notice covers it).\n"
)


def build_document() -> str:
    names = viewer_distribution_names()
    dists = list(distributions_by_names(names))
    installed = {norm(d.metadata.get("Name", "")) for d in dists}
    missing = sorted(set(names) - installed)
    # Under-inclusion is the real compliance hazard: a closure member whose
    # wheel is absent from this venv must not silently drop out of the
    # shipped notice.  The known platform-gated members (win32-only, absent
    # from a Linux dev venv) get a hand-carried entry; anything else missing
    # means the venv is stale — fail loudly.
    unaccounted = [n for n in missing if n not in FALLBACK_LICENSE_TEXTS]
    if unaccounted:
        raise SystemExit(
            "[gen-licenses] closure members not installed in this venv "
            "(their license texts cannot be harvested): "
            + ", ".join(unaccounted)
            + "\n    Run `uv sync --extra dev` and retry."
        )
    dists += [_AbsentDistribution(n, _uv_lock_version(n)) for n in missing]
    dists.sort(key=lambda d: norm(d.metadata.get("Name", "")))
    return "\n".join(
        [
            _HEADER,
            _native_binaries_section(),
            _COMPLIANCE,
            package_sections(dists, _PACKAGES_INTRO),
            full_texts(),
        ]
    )


def generate(out_path: Path | str = DEFAULT_OUT) -> Path:
    """Write the assembled viewer notice document to *out_path* and return it."""
    out = Path(out_path)
    out.write_text(build_document(), encoding="utf-8")
    return out


def main(argv: list[str]) -> int:
    out = Path(argv[1]) if len(argv) > 1 else DEFAULT_OUT
    written = generate(out)
    size = written.stat().st_size
    print(f"[gen-licenses] wrote {written} ({size:,} bytes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
